export type SolutionStep = {
  order: number;
  title: string;
  reason: string;
  difficulty: "쉬움" | "보통" | "어려움";
  time: string;
  cost: string;
  steps: string[];
  checkPoint?: string;
};

export type ProblemFaq = {
  question: string;
  answer: string;
};

export type Problem = {
  slug: string;
  title: string;
  category: string;
  description: string;
  symptoms: string[];
  keywords: string[];
  causes: string[];
  solutions: SolutionStep[];
  faqs: ProblemFaq[];
  warning?: string;
  seoTitle: string;
  seoDescription: string;
  relatedSlugs: string[];
};

type StepInput = Omit<SolutionStep, "order">;

type ProblemSeed = {
  slug: string;
  title: string;
  category: string;
  preset: string;
  keywords: string[];
  symptoms: string[];
  extraCauses: string[];
};

const step = (
  title: string,
  reason: string,
  difficulty: SolutionStep["difficulty"],
  time: string,
  steps: string[],
  checkPoint?: string,
  cost = "0원"
): StepInput => ({
  title,
  reason,
  difficulty,
  time,
  cost,
  steps,
  ...(checkPoint ? { checkPoint } : {}),
});

const withOrder = (items: StepInput[]): SolutionStep[] =>
  items.map((item, index) => ({
    order: index + 1,
    ...item,
  }));

