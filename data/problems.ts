function tokenizeForRelated(problem: Omit<Problem, "relatedSlugs">) {
  const text = [
    problem.title,
    problem.category,
    ...problem.keywords,
    ...problem.symptoms,
    ...problem.causes,
  ]
    .join(" ")
    .toLowerCase();

  return new Set(
    text
      .split(/[^0-9a-zA-Z가-힣%]+/)
      .map((word) => word.trim())
      .filter((word) => word.length >= 2)
  );
}

